import fs from 'fs';
import { createEngine } from '../game/engine.js';
const NET = JSON.parse(fs.readFileSync(new URL('../net.js', import.meta.url), 'utf8').replace(/^window\.NET=/, '').replace(/;\s*$/, ''));
const E = createEngine(NET);
const p = E.addPlayer('p1', 0);
let ev = 0; E.onEvent(() => ev++);
const t0 = Date.now();
for (let k = 0; k < 3000; k++) E.step(0.1);
const own = E.cities.find(c => E.S.owner[c.i] === 0 && c.tier >= 2);
const r = E.routeFrom(own.i, 0);
const tgt = E.cities.find(c => E.S.owner[c.i] !== 0 && isFinite(r.dist[c.i]));
console.log('send', E.command('p1', { type: 'send', src: own.i, dst: tgt.i, pct: 0.5 }));
console.log('fortify', E.command('p1', { type: 'fortify', city: own.i }));
console.log('bad send', E.command('p1', { type: 'send', src: tgt.i, dst: own.i }));
const snap = E.snapshot();
console.log('snapshot bytes', JSON.stringify(snap).length, 'convoys', snap.conv.length);
const M = createEngine(NET); M.applySnapshot(snap); M.advanceVisual(0.5);
console.log('mirror owner equal', M.S.owner.every((o, i) => o === E.S.owner[i]), 'mirror convoys', M.S.convoys.length);
while (!E.S.ended) E.step(0.1);
console.log('season', E.scores().pts, 'events', ev, 'ms', Date.now() - t0, 'p1', p.caps, p.sent, p.cp.toFixed(1));
