// Builds i18n-uk.js for the runtime translator (i18n.js):
//   dict: exact English text → Ukrainian (phrases, fragments, city and nation names)
//   pat:  sentence templates harvested from the code, as lists of their fixed parts ("Envoy sent to ", "")
//         so that "Envoy sent to Ichkeria" can be rebuilt as "Посла відправлено до Ічкерії"-style text.
// Sources: tools/i18n-uk.json (main phrases), tools/i18n-base-uk.json (names), Ukrainian city names in tools/build-net.mjs.
//   node tools/build-i18n.mjs
import fs from 'fs';
const root = new URL('../', import.meta.url);
const read = f => fs.readFileSync(new URL(f, root), 'utf8');
const norm = s => s.replace(/\s+/g, ' ').trim();

const dict = {};
for (const f of ['tools/i18n-base-uk.json', 'tools/i18n-uk.json', 'tools/i18n-extra-uk.json']) {
  if (!fs.existsSync(new URL(f, root))) continue;
  for (const [k, v] of Object.entries(JSON.parse(read(f)))) if (typeof v === 'string' && v.trim()) dict[norm(k.replace(/\\'/g, "'"))] = v.replace(/\\'/g, "'");
}
// city names: the Ukrainian list in build-net.mjs has the same order as the first cities in net.js
{
  const ua = read('tools/build-net.mjs').match(/const C = `([^`]+)`/)[1].split('|').map(s => s.split(',')[0]);
  const NET = JSON.parse(read('net.js').replace(/^window\.NET=/, '').replace(/;\s*$/, ''));
  ua.forEach((name, i) => { const en = NET.cities[i] && NET.cities[i][0]; if (en && !dict[en]) dict[en] = name.replace('ʼ', '’'); });
}

// house style: «росія» and «московія» are written in lower case
for (const k of Object.keys(dict)) dict[k] = dict[k].replace(/Росі(я|ї|ю|єю)/g, 'росі$1').replace(/Москові(я|ї|ю|єю)/g, 'москові$1');
// sentence templates: every template literal, split at HTML tags (each piece becomes its own text node)
const pat = [], seen = new Set();
for (const f of ['index.html', 'world.html', 'game/engine.js', 'server/server.mjs', 'raid-ui.js']) {
  const src = read(f);
  for (const m of src.matchAll(/`((?:[^`\\]|\\.)*)`/g)) {
    // replace ${...} (with nesting) by a marker
    let body = m[1], out = '', depth = 0;
    for (let i = 0; i < body.length; i++) {
      if (!depth && body[i] === '$' && body[i + 1] === '{') { depth = 1; i++; out += '\u0000'; continue; }
      if (depth) { if (body[i] === '{') depth++; else if (body[i] === '}') depth--; continue; }
      out += body[i];
    }
    for (const seg of out.split(/<[^>]*>/)) {
      if (!seg.includes('\u0000') || !/[A-Za-z]{3,}/.test(seg)) continue;
      const all = seg.replace(/\\'/g, "'").replace(/\\n/g, ' ').split('\u0000');
      // a value may render as its own element (cname() wraps cities in <b>), splitting the sentence on the page,
      // so every run of consecutive pieces between values is a template of its own
      for (let i = 0; i < all.length; i++) for (let j = i + 1; j < all.length; j++) {
        const parts = all.slice(i, j + 1);
        if (!/[A-Za-z]{3,}/.test(parts.join(''))) continue;
        // every fixed part must be translatable (or carry no words)
        if (!parts.every(p => !/[A-Za-z]{2,}/.test(p) || dict[norm(p)] !== undefined)) continue;
        const key = parts.join('\u0001'); if (seen.has(key)) continue; seen.add(key);
        pat.push(parts);
      }
    }
  }
}
// most specific templates first
pat.sort((a, b) => b.join('').length - a.join('').length);
// hand-written rules for sentences the code assembles from nested conditions: {n} = translated capture n, $n = as is
const rx = fs.existsSync(new URL('tools/i18n-rules-uk.json', root)) ? JSON.parse(read('tools/i18n-rules-uk.json')) : [];
fs.writeFileSync(new URL('i18n-uk.js', root), '// generated by tools/build-i18n.mjs: do not edit by hand\nwindow.SL_I18N = ' + JSON.stringify({ dict, pat, rx }) + ';\n');
console.log('dict', Object.keys(dict).length, 'templates', pat.length, 'rules', rx.length);
